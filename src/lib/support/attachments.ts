import { ATTACHMENTS_PER_MESSAGE, MAX_ATTACHMENT_BYTES, STAGED_ATTACHMENTS_PER_UPLOADER } from "./limits";

/*
 * What an image attachment may be (#680), decided by its content, never by its name or by the
 * type a browser reports: the first bytes must be the signature of a PNG, JPEG, GIF, or WebP. The
 * picker checks a file before claiming it, so a refusal names its reason at once; the server checks
 * the stored object's first bytes again before a message may carry it (attachment-store.ts),
 * because the browser is not to be trusted with either check. No SVG: an SVG is a script host.
 *
 * No imports beyond the limits, so the picker and the server share these rules and this copy.
 */

/** Mirrors support_attachments_mime_check and the bucket's allowed_mime_types. */
export const ATTACHMENT_MIME_TYPES = ["image/png", "image/jpeg", "image/gif", "image/webp"] as const;

export type AttachmentMime = (typeof ATTACHMENT_MIME_TYPES)[number];

/** How many leading bytes the signature check reads. */
export const SIGNATURE_BYTES = 16;

export function isAttachmentMime(value: unknown): value is AttachmentMime {
  return ATTACHMENT_MIME_TYPES.some((mime) => mime === value);
}

function startsWith(head: Uint8Array, signature: readonly number[], offset = 0): boolean {
  return signature.every((byte, index) => head[offset + index] === byte);
}

const PNG = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
const JPEG = [0xff, 0xd8, 0xff];
const GIF87A = [0x47, 0x49, 0x46, 0x38, 0x37, 0x61];
const GIF89A = [0x47, 0x49, 0x46, 0x38, 0x39, 0x61];
const RIFF = [0x52, 0x49, 0x46, 0x46];
const WEBP = [0x57, 0x45, 0x42, 0x50];

/** The image type the first bytes of a file declare, or null when they are no allowed signature. */
export function sniffImageType(head: Uint8Array): AttachmentMime | null {
  if (startsWith(head, PNG)) return "image/png";
  if (startsWith(head, JPEG)) return "image/jpeg";
  if (startsWith(head, GIF87A) || startsWith(head, GIF89A)) return "image/gif";
  if (startsWith(head, RIFF) && startsWith(head, WEBP, 8)) return "image/webp";
  return null;
}

// "<" after an optional byte order mark and whitespace: XML, which is what an SVG is.
function looksLikeMarkup(head: Uint8Array): boolean {
  let index = startsWith(head, [0xef, 0xbb, 0xbf]) ? 3 : 0;
  while (index < head.length && (head[index] === 0x20 || head[index] === 0x09 || head[index] === 0x0a || head[index] === 0x0d)) index += 1;
  return head[index] === 0x3c;
}

/** Why a file cannot be attached. The picker decides the first four; the server, the rest. */
export type AttachmentRefusal =
  | "svg"
  | "type"
  | "empty"
  | "too_large"
  | "count"
  | "staged_cap"
  | "thread"
  | "upload"
  | "unreadable";

export type FileFacts = Readonly<{ name: string; size: number; type: string }>;

export type AttachmentCheck =
  | Readonly<{ ok: true; mime: AttachmentMime }>
  | Readonly<{ ok: false; refusal: Extract<AttachmentRefusal, "svg" | "type" | "empty" | "too_large"> }>;

/**
 * Whether a file may be attached, from its size and its first SIGNATURE_BYTES bytes. The reported
 * type and the name only choose the wording of a refusal (an SVG says why SVG is refused); they
 * never admit a file.
 */
export function checkAttachment(file: FileFacts, head: Uint8Array): AttachmentCheck {
  if (file.size <= 0) return { ok: false, refusal: "empty" };
  if (file.size > MAX_ATTACHMENT_BYTES) return { ok: false, refusal: "too_large" };
  const mime = sniffImageType(head);
  if (mime !== null) return { ok: true, mime };
  const svg = file.type === "image/svg+xml" || /\.svgz?$/i.test(file.name) || looksLikeMarkup(head);
  return { ok: false, refusal: svg ? "svg" : "type" };
}

const DIRECTORY = /^.*[\\/]/;
const CONTROL = /[\u0000-\u001f\u007f]/g;
const MAX_FILENAME_CHARS = 255;

/**
 * The name shown beside an image: the user's filename without any directory part or control
 * characters, at most 255 characters, or "image" when nothing is left. Display text only; object
 * names are always generated by the server.
 */
export function displayFilename(name: string): string {
  const base = name.replace(DIRECTORY, "").replace(CONTROL, "").trim();
  const characters = [...base];
  const cut = characters.length > MAX_FILENAME_CHARS ? characters.slice(0, MAX_FILENAME_CHARS).join("") : base;
  return cut === "" ? "image" : cut;
}

/** "12.4 MB": a size as people compare it with what their computer says, one decimal place. */
export function formatMegabytes(bytes: number): string {
  const megabytes = bytes / (1024 * 1024);
  return `${megabytes >= 10 ? Math.round(megabytes) : Math.round(megabytes * 10) / 10} MB`;
}

const FORMATS = "PNG, JPEG, GIF, or WebP";

/**
 * What a refusal says: what happened and what to do next. `file` names the file where one is
 * involved. The picker and the server actions use the same sentences.
 */
export function attachmentRefusalMessage(refusal: AttachmentRefusal, file?: Readonly<{ name: string; size: number }>): string {
  const name = file === undefined ? "This file" : displayFilename(file.name);
  switch (refusal) {
    case "svg":
      return `${name} is an SVG image, which can carry scripts, so it cannot be attached. Attach a ${FORMATS} image instead.`;
    case "type":
      return `${name} is not a ${FORMATS} image, so it cannot be attached. Attach an image in one of those formats.`;
    case "empty":
      return `${name} is empty, so it cannot be attached. Attach an image that has content.`;
    case "too_large":
      return `${name} is ${formatMegabytes(file?.size ?? MAX_ATTACHMENT_BYTES)}, over the ${formatMegabytes(MAX_ATTACHMENT_BYTES)} limit for an image. Attach a smaller image.`;
    case "count":
      return `A message can carry up to ${ATTACHMENTS_PER_MESSAGE} images. Send this message, then attach the rest to the next one.`;
    case "staged_cap":
      return `You have ${STAGED_ATTACHMENTS_PER_UPLOADER} images waiting to be sent. Send or remove some of them, then attach this one again.`;
    case "thread":
      return "This conversation is no longer available, so the image was not attached. Reload the page to see your conversations.";
    case "upload":
      return `${name} did not finish uploading. Try attaching it again.`;
    case "unreadable":
      return `An attached image could not be read as a ${FORMATS} image, so the message was not sent. Remove the image and attach it again.`;
  }
}
