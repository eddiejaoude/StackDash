function BrandMarkSvg({ mark, ...props }: IconProps & { mark: BrandMark }) {
  return (
    <svg {...base(props)} fill={mark.fill} stroke="none">
      <path d={mark.path} />
    </svg>
  );
}

export function GitHubIcon(props: IconProps) {
  return <BrandMarkSvg mark={GITHUB_MARK} {...props} />;
}

/** A platform's mark as decoration: the platform name is always printed beside it. */
export function PlatformLogo({ platform, ...props }: IconProps & { platform: Platform }) {
  return <BrandMarkSvg mark={PLATFORM_MARKS[platform]} {...props} />;
}

